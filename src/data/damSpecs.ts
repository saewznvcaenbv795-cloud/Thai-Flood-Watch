/**
 * Helper to match dam specification by name
 */
export function getDamSpecByName(name: string): DamSpec | undefined {
  if (!name) return undefined;
  const clean = name.replace(/^เขื่อน/, '').trim();
  
  if (DAM_SPECS[clean]) return DAM_SPECS[clean];

  for (const [key, spec] of Object.entries(DAM_SPECS)) {
    if (clean.includes(key) || key.includes(clean)) {
      return spec;
    }
  }

  return undefined;
}
